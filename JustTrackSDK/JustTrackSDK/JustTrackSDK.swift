	static func computeTestGroupId(idfv: String) -> Int? {
		if idfv.count < 3 {
			return nil
		}

		guard let idfvNumber = Int(idfv.suffix(3), radix: 16) else {
			return nil
		}

		return (idfvNumber % 3) + 1
	}

	func anonymize() -> Future<Void> {
		guard isRunning() else {
			return FutureImpl().reject(JustTrackError.stopped)
		}
		let result = FutureImpl<Void>()
		getAdIds().observe { [httpClient] adIdsResult in
			switch adIdsResult {
			case let .failure(error):
				result.reject(error)
			case let .success(adIds):
				let deviceInfo = DeviceInfo(idfvProvider: self.adTrackingProvider)
				let request = DTOAnonymizeRequest(
					installInstanceId: self.installId,
					deviceId: adIds.idfa,
					idfv: deviceInfo.idfv
				)
				let userData = UserData(
					idfa: adIds.idfa,
					userId: adIds.userId,
					installId: self.installId
				)
				httpClient.sendAnonymizeRequest(request: request, userData: userData).observe { anonymizeResult in
					switch anonymizeResult {
					case let .failure(error):
						result.reject(error)
					case .success:
						result.resolve(Void())
					}
				}
			}
		}
		return result.toFuture()
	}

