	private func spawnFetchClaimTask(
		ipProtocol: IPProtocol,
		adIds: AdIds,
		connectionType: ConnectionType,
		start: Date,
		result: FutureImpl<String>
	) {
		httpClient.getSignedIpClaim(
			ipProtocol: ipProtocol,
			userData: UserData(
				idfa: adIds.idfa,
				userId: adIds.userId,
				installId: installId
			)
		).observe { response in
			switch response {
			case .failure(let error):
				_ = result.reject(error)
