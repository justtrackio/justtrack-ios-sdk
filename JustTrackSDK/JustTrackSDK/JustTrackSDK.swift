		logAggregator: LogAggregator? = nil,
		bundleId: String? = nil,
		applicationVersion: AppVersion = readAppVersion(),
		adTrackingEventPublisher: AdTrackingEventPublishing,
		sqliteDriver: SqliteDriver,
