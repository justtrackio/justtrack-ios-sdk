				do {
					let response = try DTOSignIPResponse(data: responseData)
					let timeTaken = Date().timeIntervalSince(start)
					let dimensions = LoggerFieldsImpl().with("Network", connectionType.stringValue)
					self.logger.publishMetric(ipProtocol.claimDurationMetric, timeTaken, dimensions)
					self.logger.debug("Got IP claim", LoggerFieldsImpl().with("ip", response.ip).with("type", response.type))
					_ = result.resolve(response.token)
				} catch {
					_ = result.reject(error)
				}
			}
		}
	}

	func integrateWithAdjoe() {
		AdjoeIntegration.performIntegration(
			{ (adUnit, adNetwork, placement, appId) in
				let unit: AdUnit?
				switch adUnit {
				case "BANNER":
					unit = .banner
				case "VIDEO_INTERSTITIAL":
					unit = .interstitial
				case "VIDEO_REWARDED":
					unit = .rewarded
				default:
					unit = nil
				}
				guard let unit = unit else {
					self.logger.error("Adjoe event contained invalid ad format", LoggerFieldsImpl().with("adUnit", adUnit))
					return
				}
				let impression = AdImpression(unit: unit, sdkName: "adjoe")
					.set(network: adNetwork)
					.set(placement: placement)
					.set(bundleId: appId)
				self.forward(adImpression: impression).observe { forwardResult in
					switch forwardResult {
					case let .failure(error):
						self.logger.error("Could not publish Adjoe impression", LoggerFieldsImpl().with("adUnit", adUnit).with("error", error.justTrackGetErrorDescription()))
					case .success:
						break
					}
				}
			},
			{ (message, version) in
				guard let version = version else {
					self.logger.debug("Could not integrate with Adjoe (not found)", LoggerFieldsImpl().with("message", message))
					return
				}
				self.logger.error("Could not integrate with Adjoe", LoggerFieldsImpl().with("message", message).with("version", version))
			},
			{ version in
				self.logger.info("Completed integration with Adjoe", LoggerFieldsImpl().with("version", version))
			}
		)
	}

	func forwardInAppPurchase(transactionId: String?, productId: String, totalPrice: Money) -> Bool {
		if totalPrice.value < 0 {
			logger.warn(
				"Negative revenue for product purchase",
				LoggerFieldsImpl()
					.with("productId", productId)
					.with("revenue", totalPrice.value)
					.with("currency", totalPrice.currency)
			)

			return false
		}

		do {
			try totalPrice.validate()
		} catch {
			logger.warn("Not publishing invalid product purchase: \(error)", LoggerFieldsImpl().with("productId", productId))

			return false
		}

		_ = track(
			event: JtPurchaseInternalEvent(
				jtAction: "success",
				jtProductId: productId,
				jtToken: transactionId ?? readReceiptData() ?? "",
				jtProductType: "purchase",
				revenue: totalPrice,
				happenedAt: Date()
			)
		)

		return true
	}

